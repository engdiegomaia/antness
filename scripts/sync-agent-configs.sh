#!/usr/bin/env bash
# Generate thin harness entrypoints from the canonical, vendor-neutral sources.
set -euo pipefail

if [ "$#" -gt 1 ]; then
  echo "usage: $0 [target-dir]" >&2
  exit 2
fi
if [ "$#" -eq 1 ]; then
  ROOT_DIR="$1"
else
  ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
fi
ROOT_DIR="$(cd "$ROOT_DIR" && pwd)"
cd "$ROOT_DIR"

[ -f AGENTS.md ] || { echo "AGENTS.md not found in $ROOT_DIR" >&2; exit 1; }
[ -d .ai/skills ] && [ -d .ai/agents ] && [ -d .ai/rules ] || {
  echo ".ai harness sources are incomplete" >&2
  exit 1
}

HEADER_NOTE="<!-- GENERATED by scripts/sync-agent-configs.sh. Do not edit. -->"

cat > GEMINI.md <<EOF
$HEADER_NOTE

The canonical instructions are in AGENTS.md. Read it first, then load the applicable
track instructions and on-demand skills from .ai/.

@AGENTS.md
EOF

mkdir -p .github
cat > .github/copilot-instructions.md <<EOF
$HEADER_NOTE

Read AGENTS.md first. Harness knowledge is centralized in .ai/:

- .ai/tracks/<track>/AGENTS.md — track constraints and routing
- .ai/rules/<scope>/ — mandatory shared and track rules
- .ai/skills/<scope>/<skill>/SKILL.md — on-demand task guidance
- .ai/agents/<scope>/ — review and specialist instructions
- .ai/roles/ — engineering role context
EOF

echo "Generated Gemini and Copilot pointer files from AGENTS.md."
echo "Harness sources remain in .ai; no vendor-specific directories are generated."
